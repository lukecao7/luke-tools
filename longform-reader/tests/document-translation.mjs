import assert from "node:assert/strict";
import { applyTranslationResult, figureRegions, linkedTranslationRanges, prepareTranslationGroups, sentenceParts, translationUnits, translationSchema, translationResults, translationIssue } from "../public/document-translation.mjs";

const p = (id, pageNumber, original, top) => ({ id, index: Number(id.slice(2)), pageNumber, original,
  translationVisible: true, status: "pending", language: "en", headingLevel: 0, highlights: { original: [], translation: [] },
  sourceSegments: [{ start: 0, end: original.length, text: original, rect: { left: .52, top, width: .4, height: .08 } }] });
const task = { paragraphs: [p("p-1", 5, "Overcapacity affects manufacturing", .83), p("p-2", 6, "sectors and consumer products. Demand remains weak.", .07)] };
const unchanged = JSON.stringify(task.paragraphs.map(p => ({ id: p.id, original: p.original, sourceSegments: p.sourceSegments })));
prepareTranslationGroups(task);
assert.equal(task.paragraphs[1].translationContinuationOf, "p-1");
const [unit] = translationUnits(task);
assert.equal(unit.original, "Overcapacity affects manufacturing sectors and consumer products. Demand remains weak.");
applyTranslationResult(task, unit, { segments: [{ id: "s1", translation: "产能过剩影响制造业和消费品行业。" }, { id: "s2", translation: "需求仍然疲弱。" }] });
assert.equal(task.paragraphs[0].translation, "产能过剩影响制造业和消费品行业。需求仍然疲弱。");
assert.deepEqual(linkedTranslationRanges(task, "p-2", 0, 29).ranges, [{ start: 0, end: "产能过剩影响制造业和消费品行业。".length }]);
assert.equal(JSON.stringify(task.paragraphs.map(p => ({ id: p.id, original: p.original, sourceSegments: p.sourceSegments }))), unchanged);
assert.equal(translationUnits(task).length, 0, "Completed cross-page units are not translated again");
const columns = { paragraphs: [p("p-1", 8, "The restriction affects manufacturing", .25), p("p-2", 8, "and consumer products.", .25)] };
columns.paragraphs[0].sourceSegments[0].rect.left = .05;
assert.equal(prepareTranslationGroups(columns).length, 1, "Column boundaries cannot split a sentence");
assert.equal(translationUnits(columns)[0].parts.length, 1);
const withHeading = { paragraphs: [p("p-1", 8, "An unfinished fragment", .25), { ...p("p-2", 8, "new section", .4), headingLevel: 1 }, p("p-3", 8, "another sentence", .5)] };
assert.equal(prepareTranslationGroups(withHeading).length, 0, "Do not join across a heading");
const ended = { paragraphs: [p("p-1", 5, "This paragraph is complete.", .83), p("p-2", 6, "another standalone paragraph", .07)] };
assert.equal(prepareTranslationGroups(ended).length, 0);
const heading = { paragraphs: [p("p-1", 5, "Incomplete fragment", .83), p("p-2", 6, "A different section begins.", .07)] };
assert.equal(prepareTranslationGroups(heading).length, 0);
const aligned = { paragraphs: [p("p-1", 6, "Trade creates risks. Eighty-eight percent are affected.", .3)] };
const [sentenceUnit] = translationUnits(aligned);
applyTranslationResult(aligned, sentenceUnit, { segments: [{ id: "s1", translation: "贸易带来风险。" }, { id: "s2", translation: "88%的受访者受到影响。" }] });
const target = linkedTranslationRanges(aligned, "p-1", 20, 53);
assert.equal(aligned.paragraphs[0].translation.slice(target.ranges[0].start, target.ranges[0].end), "88%的受访者受到影响。");
assert.throws(() => applyTranslationResult(aligned, sentenceUnit, { segments: [{ id: "s1", translation: "不完整" }] }), /不完整/);
const schema=translationSchema([sentenceUnit]);
assert.deepEqual(schema.properties.translations.required,['p-1']);
assert.deepEqual(schema.properties.translations.properties['p-1'].required,['s1','s2']);
const keyed=translationResults({translations:{'p-1':{s2:'88%的受访者受到影响。',s1:'贸易带来风险。'}}});
assert.equal(translationIssue(sentenceUnit,keyed.get('p-1')),null);
applyTranslationResult(aligned,sentenceUnit,keyed.get('p-1'));
assert.equal(aligned.paragraphs[0].translation,'贸易带来风险。88%的受访者受到影响。','Response object order cannot change sentence order');
assert.deepEqual(translationIssue(sentenceUnit,{segments:[{id:'s1',translation:'已完成。'}]}).missing,['s2']);
assert.ok(translationIssue(sentenceUnit,{segments:[{id:'s1',translation:'已完成。'},{id:'s1',translation:'重复编号。'}]}));
assert.ok(translationIssue(sentenceUnit,{segments:[{id:'s1',translation:'已完成。'},{id:'s2',translation:'  '}]}));
assert.ok(translationIssue(sentenceUnit,undefined));
assert.equal(sentenceParts("• Tariffs increased. Profits fell.").length, 2);

const fixture = { paragraphs: [p("p-69", 5, "Top 10 Challenges", .12), p("p-73", 5, "2025", .18), p("p-74", 5, "1. US-China relations", .21)] };
fixture.paragraphs.forEach(p => { p.sourceSegments[0].rect.left = .07; p.sourceSegments[0].rect.width = .28; });
const [figure] = figureRegions(fixture.paragraphs, [{ page: 5, block_ids: ["p-69", "p-73", "p-74"] }]);
assert.equal(figure.blockIds.length, 3);
assert.equal(figure.labels.find(l => l.original === "2025").translation, "2025");
assert.equal(figure.rect.left, .035);
fixture.figures = [figure]; fixture.paragraphs.forEach(p => { p.status = "done"; });
assert.equal(translationUnits(fixture).length, 2, "Numbers are copied locally; only English chart labels need translation");
fixture.figures.push({ ...figure, labels: figure.labels.map(l => ({ ...l, id: "copy-" + l.id })) });
assert.equal(translationUnits(fixture).length, 2, "Repeated chart labels share a translation request");
const wrapped = [p("p-1", 9, "Moved production", .2), p("p-2", 9, "closer to customers", .22)];
wrapped.forEach(p => p.sourceSegments[0].rect.height = .015);
const [joinedFigure] = figureRegions(wrapped, [{ page: 9, block_ids: ["p-1", "p-2"] }]);
assert.equal(joinedFigure.labels.length, 1);
assert.equal(joinedFigure.labels[0].original, "Moved production closer to customers");
assert.deepEqual(joinedFigure.labels[0].sources.map(s => s.paragraphId), ["p-1", "p-2"]);
console.log(JSON.stringify({ ok: true, checks: ["cross-page completeness", "source offsets unchanged", "do not join complete or unrelated paragraphs", "sentence-only highlight alignment", "reject missing translated sentences", "preserve chart numbers and layout", "deduplicate chart labels"] }));
